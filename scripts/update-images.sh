#!/usr/bin/env bash
# Regenerate or check the image digest locks (services/*/docker-compose.lock.yml).
#
#   --apply  resolve every tag in each docker-compose.yml to its current
#            registry digest and rewrite the lock as tag@digest
#   --check  resolve the same way and exit 1 if any lock would change
#
# Both modes query the registry, so neither belongs in PR CI: the monthly
# refresh job runs --apply and opens a PR. PR CI runs the offline check in
# tests/contract/contract.bats instead (each lock pins exactly the base tags).
set -euo pipefail

DEVBOX_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

case "${1:-}" in
    --apply) MODE=apply ;;
    --check) MODE=check ;;
    *) echo "Usage: $0 --apply|--check" >&2; exit 2 ;;
esac

# Interpolation placeholders: only image references are resolved.
export TAILSCALE_IP=127.0.0.1 WEBUI_SECRET_KEY=placeholder DOMAIN=example.com DEVBOX_GID=1000

drift=0
for dir in "${DEVBOX_DIR}"/services/*/; do
    [ -f "${dir}/docker-compose.yml" ] || continue
    svc=$(basename "${dir}")
    lock="${dir}/docker-compose.lock.yml"
    new=$(mktemp)
    {
        echo "# Generated by scripts/update-images.sh from docker-compose.yml. Do not edit."
        ( cd "${dir}" && docker compose -f docker-compose.yml config --lock-image-digests )
    } >"${new}"
    if cmp -s "${new}" "${lock}" 2>/dev/null; then
        echo "[ok]    services/${svc}"
        rm -f "${new}"
        continue
    fi
    if [ "${MODE}" = check ]; then
        echo "[drift] services/${svc}"
        diff -u "${lock}" "${new}" || true
        rm -f "${new}"
        drift=1
    else
        mv "${new}" "${lock}"
        chmod 0644 "${lock}"
        echo "[new]   services/${svc}"
    fi
done
exit "${drift}"
