#!/usr/bin/env bash
# shellcheck shell=bash
# =============================================================================
# Shared helpers for setup.sh and the installed helpers in ${DEVBOX_HOME}.
# Installed to ${DEVBOX_HOME}/lib/devbox-lib.sh. Unit tests source this file
# directly (tests/unit/devbox-lib.bats), so keep host mutation out of the
# pure functions and pass every path explicitly.
# =============================================================================

if [ -t 1 ]; then
    _C_RED=$'\033[0;31m' _C_GREEN=$'\033[0;32m' _C_YELLOW=$'\033[1;33m'
    _C_BLUE=$'\033[0;34m' _C_CYAN=$'\033[0;36m' _C_NC=$'\033[0m'
else
    _C_RED='' _C_GREEN='' _C_YELLOW='' _C_BLUE='' _C_CYAN='' _C_NC=''
fi

log()   { printf '%s[ok]%s %s\n' "${_C_GREEN}" "${_C_NC}" "$*"; }
info()  { printf '%s[..]%s %s\n' "${_C_BLUE}" "${_C_NC}" "$*"; }
warn()  { printf '%s[!!]%s %s\n' "${_C_YELLOW}" "${_C_NC}" "$*" >&2; }
die()   { printf '%s[xx]%s %s\n' "${_C_RED}" "${_C_NC}" "$*" >&2; exit 1; }
phase() { printf '\n%s== %s ==%s\n' "${_C_CYAN}" "$*" "${_C_NC}"; }

# generate_secret [length] — alphanumeric string from the openssl CSPRNG.
generate_secret() {
    local len="${1:-32}" out=""
    while [ "${#out}" -lt "${len}" ]; do
        out+=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9')
    done
    printf '%s' "${out:0:${len}}"
}

# write_atomic <dest> <mode> — copy stdin to <dest> via a temp file in the
# same directory, so readers never observe a partial file.
write_atomic() {
    local dest="$1" mode="$2" tmp
    tmp=$(mktemp "${dest}.XXXXXX")
    if ! cat >"${tmp}"; then
        rm -f "${tmp}"
        return 1
    fi
    chmod "${mode}" "${tmp}"
    mv -f "${tmp}" "${dest}"
}

# render_template <template> <dest> <envsubst-whitelist> [mode]
# Always re-renders. Use for files derived from persisted state.
render_template() {
    envsubst "$3" <"$1" | write_atomic "$2" "${4:-0600}"
}

# render_once <template> <dest> <envsubst-whitelist> — renders only when
# <dest> is absent. Use for operator-owned files (.env) that must survive
# re-runs.
render_once() {
    [ -e "$2" ] && return 0
    render_template "$1" "$2" "$3" 0600
}

# Credential files hold one "user:password" line, mode 0600.
credential_user() { head -n1 "$1" | cut -d: -f1; }
credential_pass() { head -n1 "$1" | cut -d: -f2-; }

# ensure_credential <file> <user> — create the credential once; later runs
# keep it, so derived files (htpasswd hashes) always match what operators see.
ensure_credential() {
    local file="$1" user="$2"
    [ -s "${file}" ] && return 0
    install -d -m 0700 "$(dirname "${file}")"
    printf '%s:%s\n' "${user}" "$(generate_secret 32)" | write_atomic "${file}" 0600
}

# rotate_credential <file> <user> — replace the credential unconditionally.
rotate_credential() {
    install -d -m 0700 "$(dirname "$1")"
    printf '%s:%s\n' "$2" "$(generate_secret 32)" | write_atomic "$1" 0600
}

# render_basic_auth <middleware-name> <credential-file> <dest>
# Writes a Traefik file-provider basicAuth middleware, mode 0640: Traefik
# reads it through the operator's group (group_add in the compose file). The
# file provider takes the hash verbatim: `$$` escaping applies to Compose
# labels only and would corrupt it. apr1 suits 32-char random passwords.
render_basic_auth() {
    local name="$1" cred="$2" dest="$3" user hash
    user=$(credential_user "${cred}")
    hash=$(credential_pass "${cred}" | openssl passwd -apr1 -stdin)
    write_atomic "${dest}" 0640 <<EOF
# Generated by devbox from ${cred##*/}. Do not edit: rotate the credential.
http:
  middlewares:
    ${name}:
      basicAuth:
        users:
          - "${user}:${hash}"
        removeHeader: true
EOF
}

# env_get <file> <KEY> — print the last KEY=value without sourcing the file.
env_get() {
    [ -f "$1" ] || return 0
    sed -n "s/^${2}=//p" "$1" | tail -n1
}

# env_set <file> <KEY> <VALUE> — upsert in place, preserving order and mode.
env_set() {
    local file="$1" mode=0600
    if [ -f "${file}" ]; then
        mode=$(stat -c %a "${file}")
    else
        : >"${file}"
    fi
    K="$2" V="$3" awk '
        index($0, ENVIRON["K"] "=") == 1 { if (!done) print ENVIRON["K"] "=" ENVIRON["V"]; done = 1; next }
        { print }
        END { if (!done) print ENVIRON["K"] "=" ENVIRON["V"] }
    ' "${file}" | write_atomic "${file}" "${mode}"
}

# env_default <file> <KEY> <VALUE> — set only when KEY is absent, so operator
# overrides survive re-runs.
env_default() {
    if [ -f "$1" ] && grep -q "^${2}=" "$1"; then
        return 0
    fi
    env_set "$@"
}

# env_unset <file> <KEY>...
env_unset() {
    local file="$1" mode key
    shift
    [ -f "${file}" ] || return 0
    mode=$(stat -c %a "${file}")
    for key in "$@"; do
        grep -v "^${key}=" "${file}" | write_atomic "${file}" "${mode}" || true
    done
}

# compose_file_chain <service-dir> <enable-https> <gpu> — the COMPOSE_FILE
# value for a service: base, then optional overlays, then the digest lock.
compose_file_chain() {
    local dir="$1" https="$2" gpu="$3" chain="docker-compose.yml"
    if [ "${https}" = "true" ] && [ -f "${dir}/docker-compose.https.yml" ]; then
        chain+=":docker-compose.https.yml"
    fi
    if [ "${gpu}" = "nvidia" ] && [ -f "${dir}/docker-compose.gpu.yml" ]; then
        chain+=":docker-compose.gpu.yml"
    fi
    if [ -f "${dir}/docker-compose.lock.yml" ]; then
        chain+=":docker-compose.lock.yml"
    fi
    printf '%s' "${chain}"
}

# Excluded paths are neither copied nor deleted: dotfiles (.env, editor and
# tool state), generated or operator-owned files, and templates (rendered
# from the repo by setup.sh).
RSYNC_EXCLUDES=(--exclude='.*' --exclude='ovh.env' --exclude='letsencrypt/'
    --exclude='logs/' --exclude='/dynamic/*-auth.yml' --exclude='*.template')

# rsync_install <src> <dest> [rsync-options...] — mirror a tracked service
# tree into the install, protecting RSYNC_EXCLUDES from --delete.
rsync_install() {
    local src="$1" dest="$2"
    shift 2
    [ -d "${dest}" ] || install -d -m 0755 "${dest}"
    # --chmod: a checkout made with umask 077 must not yield files Traefik
    # (root without capabilities) cannot read.
    rsync -a --delete --chmod=D0755,F0644 "${RSYNC_EXCLUDES[@]}" "$@" "${src}/" "${dest}/"
}

# collision_guard <devbox-home> <repo-dir> — refuse to install into a tree
# that holds anything devbox does not own, unless it is a prior install
# (contract + marker both present).
collision_guard() {
    local home="$1" repo="$2" entry name allowed f
    [ -d "${home}" ] || return 0
    [ -n "$(ls -A "${home}" 2>/dev/null)" ] || return 0
    if [ -f "${home}/lib/devbox-contract.sh" ] && [ -f "${home}/lib/.devbox-marker" ]; then
        return 0
    fi
    allowed=" lib systemd .secrets exegol-workspace ${DEVBOX_SERVICES[*]} "
    for f in "${repo}"/scripts/host/*.sh; do
        allowed+="${f##*/} "
    done
    local offenders=()
    for entry in "${home}"/* "${home}"/.[!.]*; do
        [ -e "${entry}" ] || continue
        name="${entry##*/}"
        case "${allowed}" in
            *" ${name} "*) ;;
            *) offenders+=("${name}") ;;
        esac
    done
    if [ ${#offenders[@]} -gt 0 ]; then
        printf 'Refusing to install into %s: not a devbox tree. Unexpected entries:\n' "${home}" >&2
        printf '  %s\n' "${offenders[@]}" >&2
        return 1
    fi
}

# gpg_export_pinned <key-file> <fingerprint> <out> — import <key-file> into a
# throwaway keyring and export only the key whose primary fingerprint is
# pinned. Fails if the file does not carry that key.
gpg_export_pinned() {
    local key="$1" fpr="$2" out="$3" gnupg actual
    gnupg=$(mktemp -d)
    if ! gpg --homedir "${gnupg}" --batch --quiet --import "${key}" 2>/dev/null; then
        rm -rf "${gnupg}"
        return 1
    fi
    actual=$(gpg --homedir "${gnupg}" --batch --with-colons --list-keys "${fpr}" 2>/dev/null \
        | awk -F: '$1 == "fpr" { print $10; exit }')
    if [ "${actual}" != "${fpr}" ]; then
        rm -rf "${gnupg}"
        return 1
    fi
    gpg --homedir "${gnupg}" --batch --export "${fpr}" | write_atomic "${out}" 0644
    rm -rf "${gnupg}"
}

# apt_add_repo <name> <key-url> <fingerprint> <uri> <suite> <component>
# Adds a deb822 source signed by a fingerprint-verified keyring.
apt_add_repo() {
    local name="$1" key_url="$2" fpr="$3" uri="$4" suite="$5" comp="$6"
    local keyring="/usr/share/keyrings/${name}-archive-keyring.gpg" tmp
    tmp=$(mktemp)
    if ! curl -fsSL --proto '=https' --tlsv1.2 "${key_url}" -o "${tmp}"; then
        rm -f "${tmp}"
        die "Could not download the ${name} signing key from ${key_url}"
    fi
    if ! gpg_export_pinned "${tmp}" "${fpr}" "${keyring}"; then
        rm -f "${tmp}"
        die "The ${name} signing key at ${key_url} does not match pinned fingerprint ${fpr}. Refusing to trust it (see scripts/update-pins.sh)."
    fi
    rm -f "${tmp}"
    # A legacy one-line source for the same repo makes apt refuse both.
    [ -f "/etc/apt/sources.list.d/${name}.list" ] && mv "/etc/apt/sources.list.d/${name}.list" "/etc/apt/sources.list.d/${name}.list.disabled"
    write_atomic "/etc/apt/sources.list.d/${name}.sources" 0644 <<EOF
Types: deb
URIs: ${uri}
Suites: ${suite}
Components: ${comp}
Signed-By: ${keyring}
EOF
}

# wait_for_listen <port> <seconds> [process-regex] — succeed once a TCP
# listener is up on <port>, owned by a process matching the regex if given
# (needs root to see other users' processes).
wait_for_listen() {
    local i
    for (( i = 0; i < $2; i++ )); do
        if ss -Hltnp "( sport = :$1 )" 2>/dev/null | grep -qE "${3:-.}"; then
            return 0
        fi
        sleep 1
    done
    return 1
}
